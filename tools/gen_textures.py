ITEMS = []
for mat in ("emerald", "obsidian", "amethyst"):
    for tool in ("sword", "pickaxe", "axe", "shovel", "hoe"):
        ITEMS.append((f"{mat}_{tool}", tool, mat))
for mat in ("iron", "diamond", "netherite"):
    for tool in ("hammer", "excavator", "lumber_axe"):
        ITEMS.append((f"{mat}_{tool}", tool, mat))
for mat in ("diamond", "netherite"):
    ITEMS.append((f"{mat}_paxel", "paxel", mat))


def hex_rgba(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def parse(shape):
    rows = [r for r in shape.strip("\n").split("\n")]
    assert len(rows) == 16, (len(rows))
    for r in rows:
        assert len(r) == 16, r
    return rows


def render(shape_name, mat):
    rows = parse(SHAPES[shape_name])
    head = PALETTES[mat]
    wood = PALETTES["wood"]
    gem = PALETTES["diamond"] if mat != "diamond" else PALETTES["emerald"]
    # sword guard uses a dark metal colour
    guard = PALETTES["netherite"] if mat != "netherite" else PALETTES["iron"]

    def kind(x, y):
        if 0 <= x < 16 and 0 <= y < 16:
            return rows[y][x]
        return "."

    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    px = img.load()
    for y in range(16):
        for x in range(16):
            k = kind(x, y)
            if k == ".":
                continue
            pal = {"M": head, "W": wood, "G": guard}[k]
            same = lambda dx, dy: kind(x + dx, y + dy) == k
            if not same(0, -1) or not same(-1, 0):
                c = pal[0]
            elif not same(0, 1) or not same(1, 0):
                c = pal[2]
            else:
                c = pal[1]
            px[x, y] = hex_rgba(c)
    # outlines: empty cells touching a filled cell (edge-adjacent)
    for y in range(16):
        for x in range(16):
            if kind(x, y) != ".":
                continue
            neigh = [kind(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
            if "M" in neigh:
                px[x, y] = hex_rgba(head[3])
            elif "G" in neigh:
                px[x, y] = hex_rgba(guard[3])
            elif "W" in neigh:
                px[x, y] = hex_rgba(wood[3])
    return img


def main():
    os.makedirs(OUT, exist_ok=True)
    cols = 9
    rows = (len(ITEMS) + cols - 1) // cols
    preview = Image.new("RGBA", (18 * cols, 18 * rows), (0, 0, 0, 0))
    for i, (name, shape, mat) in enumerate(ITEMS):
        img = render(shape, mat)
        img.save(os.path.join(OUT, name + ".png"))
        preview.paste(img, (18 * (i % cols) + 1, 18 * (i // cols) + 1))
    if len(sys.argv) > 1:
        bg = Image.new("RGBA", preview.size, (139, 139, 139, 255))
        bg.alpha_composite(preview)
        bg.resize((preview.width * 8, preview.height * 8), Image.NEAREST).save(sys.argv[1])
    print(f"wrote {len(ITEMS)} textures")


if __name__ == "__main__":
    main()
